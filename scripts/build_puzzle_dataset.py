#!/usr/bin/env python3
"""Build the small, browser-safe puzzle dataset used by GitHub Pages."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.render_puzzle_md import attempts_of, due_at, original_fen, puzzle_id, status_of


def compact(puzzle):
    attempts = attempts_of(puzzle)
    failures = sum(not bool(a.get("found")) for a in attempts)
    prompt_type = puzzle.get("prompt_type", "best_move")
    expected = puzzle.get("refutation") if prompt_type == "refutation" else puzzle.get("best_move")
    expected_san = puzzle.get("refutation_san") if prompt_type == "refutation" else puzzle.get("best_move_san")
    original_color = original_fen(puzzle).split()[1]
    return {
        "id": puzzle_id(puzzle),
        "fen": original_fen(puzzle),
        "prompt": puzzle.get("prompt") or "Find the best move in this position.",
        "expectedMove": expected,
        "expectedSan": expected_san,
        "setupMove": puzzle.get("move_played") if prompt_type == "refutation" else None,
        "setupSan": puzzle.get("move_played_san") if prompt_type == "refutation" else None,
        "color": ({"w": "b", "b": "w"}[original_color]
                  if prompt_type == "refutation" else original_color),
        "category": puzzle.get("category") or puzzle.get("puzzle_type") or "other",
        "dueAt": due_at(attempts).isoformat() if due_at(attempts) else None,
        "attemptSummary": {
            "count": len(attempts), "failures": failures,
            "lastFound": bool(attempts[-1].get("found")) if attempts else None,
            "lastAt": attempts[-1].get("timestamp") if attempts else None,
            "status": status_of(attempts),
        },
    }


def build(source=Path("puzzles.json")):
    raw = json.loads(Path(source).read_text(encoding="utf-8"))
    puzzles = raw if isinstance(raw, list) else raw.get("puzzles", [])
    return {"schemaVersion": 1, "puzzles": [compact(p) for p in puzzles]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default="puzzles.json")
    parser.add_argument("--output", default="docs/puzzles-data.js")
    args = parser.parse_args()
    data = build(Path(args.source))
    Path(args.output).write_text(
        "// Generated by scripts/build_puzzle_dataset.py; do not edit.\n"
        "window.PUZZLE_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(data['puzzles'])} puzzles to {args.output}")


if __name__ == "__main__":
    main()
